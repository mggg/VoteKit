from __future__ import annotations

from abc import abstractmethod
from collections.abc import Callable

import numpy as np

from votekit.elections.election_state import ElectionState
from votekit.models import Election
from votekit.pref_profile import ProfileError, RankProfile
from votekit.types import CandidateNumericDict


class RankingElection(Election[RankProfile]):
    """
    Abstract class for ranking election types. Validates that profile contains ranked ballots.

    Args:
        profile (RankProfile): The initial profile of ballots.
        score_function (Callable[[RankProfile], CandidateNumericDict], optional):
            A function that converts profiles to a score dictionary mapping candidates to
            their current score. Used in creating ElectionState objects and sorting candidates in
            Round 0. If None, no score dictionary is saved and all candidates are tied in Round 0.
            Defaults to None.
        sort_high_low (bool, optional): How to sort candidates based on `score_function`. True sorts
            from high to low. Defaults to True.

    Attributes:
        election_states (list[ElectionState]): a list of election states, one for each round of
            the election. The list is 0 indexed, so the initial state is stored at index 0, round 1
            at 1, etc.
        score_function (Callable[[RankProfile], CandidateNumericDict], optional):
            A function that converts profiles to a score dictionary mapping candidates to
            their current score. Used in creating ElectionState objects. Defaults to None.
            Candidates can be strings, integers, or mix of both.
        length (int): the number of rounds of the election.
    """

    def __init__(
        self,
        profile: RankProfile,
        n_seats: int = 1,
        score_function: Callable[[RankProfile], CandidateNumericDict] | None = None,
        sort_high_low: bool = True,
    ):
        if n_seats <= 0:
            raise ValueError("n_seats must be positive.")
        self.n_seats = n_seats
        super().__init__(profile, score_function, sort_high_low)

    def _validate_params(self, profile: RankProfile):
        """
        Validates election parameters against the profile.

        Args:
            profile (RankProfile): Profile of ballots.

        Raises:
            ValueError: If there are not enough candidates who received votes to fill
                the requested seats.
        """
        if len(profile.candidates_cast) < self.n_seats:
            raise ValueError("Not enough candidates received votes to be elected.")

    def _validate_profile(self, profile: RankProfile):
        """
        Validate that the profile is nonempty and each ballot ranks at least one candidate.

        Args:
            profile (RankProfile): Profile of ballots.
        """
        if not isinstance(profile, RankProfile):
            raise ProfileError("Profile must be of type RankProfile.")

        matrix = profile._matrix
        if not len(matrix):
            raise ProfileError("Profile must contain at least one ballot.")

        if profile.max_ranking_length < 1:
            raise ProfileError("Profile must contain at least one ranked candidate.")

        unranked_rows = np.flatnonzero(~matrix.has_ranked_candidates())
        if unranked_rows.size:
            row = int(unranked_rows[0])
            ballot = profile.get_ballot(row)
            raise TypeError(f"Ballot {ballot} has no ranking.")

    @abstractmethod
    def _run_step(
        self, profile: RankProfile, prev_state: ElectionState, store_states=False
    ) -> RankProfile:
        """
        Run one step of an election from the given profile and previous state.

        Args:
            profile (RankProfile): Profile of ballots.
            prev_state (ElectionState): The previous ElectionState.
            store_states (bool, optional): True if `self.election_states` should be updated with the
                ElectionState generated by this round. This should only be True when used by
                `self._run_election()`. Defaults to False.

        Returns:
            RankProfile: The profile of ballots after the round is completed.
        """
        pass

    @abstractmethod
    def _is_finished(self) -> bool:
        """
        Returns True if election is finished, False if another round is needed.
        """
        pass
